CREATE TABLE tetools.admin_sessions_log (
  ID                             INTEGER GENERATED ALWAYS AS IDENTITY,
  LOG_DATE                       DATE             NOT NULL,
  TERMNTN_REQUEST_ACCEPTED       CHAR(1)          NOT NULL,
  TERMNTN_REQUEST_STATUS         CHAR(1)          NOT NULL,   -- STATUS CAN BE: 'O'-OPEN, 'K'-KILLED, 'C'-WAITING-FOR-CONFIRMATION, 'R'-RETRACTED, 'D'-DENIED, 'X'-EXECUTING, 'E'-ERROR, 'M'-MARKED-FOR-KILL, 'G'-GRACE-TIME, 'T'-TIMED-OUT
  INVOKING_USERNAME              VARCHAR2(128)    NOT NULL,
  INVOKING_USER_DETAILS          VARCHAR2(128)    NOT NULL,   -- SID, SERIAL#, PID
  TARGET_USERNAME                VARCHAR2(128)    NOT NULL,
  TARGET_USER_DETAILS            VARCHAR2(128)    NOT NULL,   -- SID, SERIAL#, PID
  INVOKING_USER_ROLES            VARCHAR2(1000),              -- GRANTED ROLES TO INVOKING USER
  INVOKING_USER_ISADMIN          CHAR(1),
  TARGET_USER_ISADMIN            CHAR(1),
  TARGET_USER_ROLES              VARCHAR2(1000),              -- GRANTED ROLES TO TARGET USER,
  CONFMTN_REQUIRED               CHAR(1),
  CONFMTN_REQUIRED_DATE          DATE,
  CONFMTN_GIVEN                  CHAR(1),
  CONFMTN_GIVEN_DATE             DATE,
  CONFMTN_GIVEN_BY_USER          VARCHAR2(128),
  SESSION_MARKED_FOR_TERMNTN     CHAR(1),
  SESSION_TERMNTND               CHAR(1),
  TARGET_USER_SQLSTMNT           VARCHAR2(1000),
  TARGET_USER_SQLSTMNTL          CLOB,
  TARGET_USER_SQLID              VARCHAR2(13),
  TARGET_USER_SQLID_CHILD#       NUMBER,
  TARGET_USER_SQL_CPU_TIME       NUMBER,
  TARGET_USER_SQL_PHYS_READ      NUMBER,
  TARGET_USER_SQL_PHYS_WRITE     NUMBER,
  TERMNTN_REQUEST_DENIED_REASON  VARCHAR2(200),
  TERMNTN_REQUEST_DENIED_BY      VARCHAR2(200),
  TERMNTN_REQUEST_DENIED_DATE    DATE,
  CONSTRAINT ADMIN_SESSIONS_LOG_IUD CHECK (INVOKING_USER_DETAILS IS JSON),
  CONSTRAINT ADMIN_SESSIONS_LOG_TUD CHECK (TARGET_USER_DETAILS IS JSON),
  CONSTRAINT ADMIN_SESSIONS_LOG_IUR CHECK (INVOKING_USER_ROLES IS JSON),
  CONSTRAINT ADMIN_SESSIONS_LOG_TUR CHECK (TARGET_USER_ROLES IS JSON),
  CONSTRAINT ADMIN_SESSIONS_LOG_TRS CHECK (TERMNTN_REQUEST_STATUS IN ('X', 'E','O','K','C','R','D','T','G')) ENABLE,
  CONSTRAINT ADMIN_SESSIONS_LOG_IUA CHECK (INVOKING_USER_ISADMIN IN ('Y','N')) ENABLE,
  CONSTRAINT ADMIN_SESSIONS_LOG_TUA CHECK (TARGET_USER_ISADMIN IN ('Y','N')) ENABLE,
  CONSTRAINT ADMIN_SESSIONS_LOG_CRV CHECK (CONFMTN_REQUIRED IN ('Y','N')) ENABLE,
  CONSTRAINT ADMIN_SESSIONS_LOG_CGV CHECK (CONFMTN_GIVEN IN ('Y','N')) ENABLE,
  CONSTRAINT ADMIN_SESSIONS_LOG_SMT CHECK (SESSION_MARKED_FOR_TERMNTN IN ('Y','N')) ENABLE,
  CONSTRAINT ADMIN_SESSIONS_LOG_STV CHECK (SESSION_TERMNTND IN ('Y','N')) ENABLE,
  CONSTRAINT ADMIN_SESSIONS_LOG_TRA CHECK (TERMNTN_REQUEST_ACCEPTED IN ('Y','N')) ENABLE
);


