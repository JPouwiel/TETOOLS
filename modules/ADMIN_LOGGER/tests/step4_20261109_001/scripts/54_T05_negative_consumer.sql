DECLARE l_n NUMBER; l_error VARCHAR2(4000);
BEGIN
  IF USER IN ('TETOOLS','SYS','SYSTEM') THEN RAISE_APPLICATION_ERROR(-20532,'Separate negative principal required'); END IF;
  BEGIN
    EXECUTE IMMEDIATE 'BEGIN tetools.admin_logger.LOG_INFO_FORCE(:tag,:data); END;'
      USING 'S4_&&TEST_RUN_ID._T05_NEG','NEGATIVE_API_MUST_NOT_SUCCEED';
    RAISE_APPLICATION_ERROR(-20533,'FAIL: negative principal executed logger');
  EXCEPTION WHEN OTHERS THEN
    l_error:=SQLERRM;
    IF NOT (SQLCODE=-1031 OR (SQLCODE=-6550 AND INSTR(l_error,'PLS-00201')>0)) THEN RAISE; END IF;
    DBMS_OUTPUT.PUT_LINE('EXPECTED_API_DENIAL '||l_error);
  END;
  BEGIN
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM tetools.admin_logger_log' INTO l_n;
    RAISE_APPLICATION_ERROR(-20534,'FAIL: negative principal read source table');
  EXCEPTION WHEN OTHERS THEN
    IF SQLCODE NOT IN (-942,-1031) THEN RAISE; END IF;
    DBMS_OUTPUT.PUT_LINE('EXPECTED_TABLE_DENIAL '||SQLERRM);
  END;
  DBMS_OUTPUT.PUT_LINE('DENIAL_PROBES_COMPLETED; verify object existence/grant inventory independently; maintenance isolation still separate');
