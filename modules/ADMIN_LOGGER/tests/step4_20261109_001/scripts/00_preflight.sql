-- READ-ONLY preflight; MUST run under a separately authorized SQL client session.
WHENEVER OSERROR EXIT FAILURE ROLLBACK
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET VERIFY OFF SERVEROUTPUT ON FEEDBACK ON
PROMPT TETOOLS STEP4 PRE-FLIGHT (no DDL)
DECLARE
  l_schema VARCHAR2(128) := SYS_CONTEXT('USERENV','CURRENT_SCHEMA');
  l_pdb    VARCHAR2(128) := SYS_CONTEXT('USERENV','CON_NAME');
  l_db     VARCHAR2(128) := SYS_CONTEXT('USERENV','DB_UNIQUE_NAME');
  l_con    NUMBER := TO_NUMBER(SYS_CONTEXT('USERENV','CON_ID'));
  l_count  NUMBER;
BEGIN
  IF '&&EXECUTION_APPROVED' <> 'YES' OR '&&DBA_ENV_APPROVED' <> 'YES' THEN
    RAISE_APPLICATION_ERROR(-20001,'NO ORACLE EXECUTION AUTHORIZATION');
  END IF;
  IF '&&TARGET_SCHEMA' <> 'TETOOLS' OR USER <> 'TETOOLS' OR l_schema <> 'TETOOLS' THEN
    RAISE_APPLICATION_ERROR(-20002,'WRONG SCHEMA: TETOOLS required');
  END IF;
  IF '&&TARGET_PDB' = 'UNVERIFIED' OR l_pdb <> '&&TARGET_PDB' OR l_con <> TO_NUMBER('&&TARGET_CON_ID') THEN
    RAISE_APPLICATION_ERROR(-20003,'PDB/CON_ID mismatch');
  END IF;
  IF '&&TARGET_DB_UNIQUE_NAME' = 'UNVERIFIED' OR l_db <> '&&TARGET_DB_UNIQUE_NAME' THEN
    RAISE_APPLICATION_ERROR(-20004,'DB_UNIQUE_NAME mismatch');
  END IF;
  IF l_con = 1 THEN RAISE_APPLICATION_ERROR(-20005,'CDB ROOT forbidden'); END IF;
  SELECT COUNT(*) INTO l_count FROM USER_OBJECTS WHERE OBJECT_NAME LIKE 'ADMIN_LOGGER%';
  IF l_count > 0 THEN
    RAISE_APPLICATION_ERROR(-20006,'SCHEMA NOT EMPTY: '||l_count||' ADMIN_LOGGER objects');
  END IF;
  DBMS_OUTPUT.PUT_LINE('PREFLIGHT PASS, DB='||l_db||', PDB='||l_pdb||', CON_ID='||l_con);
END;
/
